  ///
  /// 如果输入为 null 或空，返回原值。
  /// 翻译是尽力而为的，无法翻译的部分保留原文。
  static String? translate(String? notes) {
    if (notes == null || notes.isEmpty) return notes;

    var result = notes;

    // 先处理完整句子/短语（按长度降序，避免短词替换破坏长句）
    for (final entry in _phraseTranslations) {
      result = result.replaceAllMapped(entry.key, (m) => entry.value);
    }

    // 再处理单词/术语
    for (final entry in _wordTranslations) {
      result = result.replaceAllMapped(entry.key, (m) => entry.value);
    }

    return result;
  }

