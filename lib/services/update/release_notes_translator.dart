/// Release Notes 英中翻译器。
///
/// 对 GitHub Release 的更新说明进行本地化翻译。
/// 采用字典替换方式，处理常见的英文术语、短语和句子模式。
/// 技术术语（如 Vulkan, JIT, ASTC 等）保留原文。
